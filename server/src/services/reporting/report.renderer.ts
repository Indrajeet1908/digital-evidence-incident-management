/**
 * Report renderer for PDF and HTML export.
 * Uses pdfkit for PDF generation and produces safe HTML output.
 *
 * SECURITY:
 * - All database/AI content treated as untrusted display content
 * - No template injection, no eval, no innerHTML without sanitization
 * - XSS-safe content rendering
 */

import PDFDocument from 'pdfkit';
import type { InvestigationReport } from '../../types/report.types';

/**
 * Escape HTML special characters for safe rendering.
 */
function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Safe text for PDF (strip control characters).
 */
function safePdfText(text: string | null | undefined): string {
  if (!text) return '';
  return String(text).replace(/[\x00-\x08\x0B\x0C\x0E-\x1F]/g, '');
}

export class ReportRenderer {
  /**
   * Render a structured report to PDF format.
   * Returns a Buffer containing the PDF data.
   */
  async renderPDF(report: InvestigationReport): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      try {
        const doc = new PDFDocument({
          size: 'A4',
          margins: { top: 50, bottom: 50, left: 60, right: 60 },
          info: {
            Title: `Investigation Report - ${report.reportMetadata.reportType}`,
            Author: report.reportMetadata.generatedBy.name,
            Subject: `Case: ${report.reportMetadata.caseNumber ?? 'N/A'}`,
            Creator: 'Digital Evidence Platform',
          },
        });

        const chunks: Buffer[] = [];
        doc.on('data', (chunk: Buffer) => chunks.push(chunk));
        doc.on('end', () => resolve(Buffer.concat(chunks)));
        doc.on('error', (err: Error) => reject(err));

        // ─── Title Page ────────────────────────────────────
        doc
          .fontSize(22)
          .font('Helvetica-Bold')
          .text('INVESTIGATION REPORT', { align: 'center' });
        doc.moveDown(0.5);
        doc
          .fontSize(14)
          .font('Helvetica')
          .text(safePdfText(report.reportMetadata.reportType.replace(/_/g, ' ')), {
            align: 'center',
          });
        doc.moveDown(1);

        // Metadata block
        doc.fontSize(9).font('Helvetica');
        doc.text(`Generated: ${report.reportMetadata.generatedAt}`);
        doc.text(`Generated By: ${safePdfText(report.reportMetadata.generatedBy.name)} (${safePdfText(report.reportMetadata.generatedBy.role)})`);
        if (report.reportMetadata.caseNumber) {
          doc.text(`Case: ${safePdfText(report.reportMetadata.caseNumber)}`);
        }
        if (report.reportMetadata.incidentNumber) {
          doc.text(`Incident: ${safePdfText(report.reportMetadata.incidentNumber)}`);
        }
        if (report.reportMetadata.evidenceNumber) {
          doc.text(`Evidence: ${safePdfText(report.reportMetadata.evidenceNumber)}`);
        }
        doc.text(`Classification: ${safePdfText(report.reportMetadata.classification)}`);
        doc.moveDown(1);

        // Horizontal rule
        this.pdfHorizontalRule(doc);

        // ─── Case Section ──────────────────────────────────
        if (report.case) {
          this.pdfSectionHeader(doc, '1. CASE IDENTIFICATION');
          doc.fontSize(9);
          doc.text(`Case Number: ${safePdfText(report.case.caseNumber)}`);
          doc.text(`Title: ${safePdfText(report.case.title)}`);
          doc.text(`Status: ${report.case.status} | Priority: ${report.case.priority} | Severity: ${report.case.severity}`);
          doc.text(`Type: ${report.case.caseType} | Category: ${report.case.category}`);
          doc.text(`Classification: ${report.case.classification}`);
          doc.text(`Created: ${report.case.createdAt}`);
          if (report.case.leadInvestigator) {
            doc.text(`Lead Investigator: ${safePdfText(report.case.leadInvestigator)}`);
          }
          if (report.case.description) {
            doc.moveDown(0.3);
            doc.text(`Description: ${safePdfText(report.case.description)}`);
          }
          doc.moveDown(0.5);
        }

        // ─── Incidents Section ──────────────────────────────
        if (report.incidents.length > 0) {
          this.pdfSectionHeader(doc, '2. INCIDENTS');
          for (const inc of report.incidents) {
            doc.fontSize(9).font('Helvetica-Bold');
            doc.text(`${safePdfText(inc.incidentNumber)}: ${safePdfText(inc.title)}`);
            doc.font('Helvetica');
            doc.text(`  Type: ${inc.type} | Category: ${inc.category} | Severity: ${inc.severity} | Status: ${inc.status}`);
            if (inc.description) {
              doc.text(`  Description: ${safePdfText(inc.description)}`);
            }
            if (inc.aiClassification) {
              doc.fillColor('#b45309').text(`  [AI Advisory] Classification: ${safePdfText(inc.aiClassification.classification)} (Confidence: ${(inc.aiClassification.confidence * 100).toFixed(1)}%)`);
              doc.fillColor('#000000');
            }
            doc.moveDown(0.3);
          }
        }

        // ─── Evidence Inventory ─────────────────────────────
        if (report.evidence.length > 0) {
          this.pdfSectionHeader(doc, '3. EVIDENCE INVENTORY');
          for (const ev of report.evidence) {
            doc.fontSize(9).font('Helvetica-Bold');
            doc.text(`${safePdfText(ev.evidenceNumber)}: ${safePdfText(ev.originalFilename)}`);
            doc.font('Helvetica');
            doc.text(`  Type: ${ev.evidenceType} | Source: ${ev.source} | Size: ${ev.fileSize} bytes`);
            doc.text(`  SHA-256: ${ev.sha256}`);
            doc.text(`  Uploaded By: ${safePdfText(ev.uploadedBy)} | Created: ${ev.createdAt}`);
            doc.moveDown(0.2);
          }
        }

        // ─── Integrity Section ──────────────────────────────
        if (report.integrity.length > 0) {
          this.pdfSectionHeader(doc, '4. EVIDENCE INTEGRITY');
          for (const integ of report.integrity) {
            doc.fontSize(9);
            doc.text(`${safePdfText(integ.evidenceNumber)}: ${integ.integrityStatus}`);
            doc.text(`  Stored SHA-256: ${integ.storedSha256}`);
            if (integ.latestCalculatedSha256) {
              doc.text(`  Calculated SHA-256: ${integ.latestCalculatedSha256}`);
            }
            doc.text(`  ${safePdfText(integ.note)}`);
            doc.moveDown(0.2);
          }
        }

        // ─── Custody Chain ──────────────────────────────────
        if (report.custody.length > 0) {
          this.pdfSectionHeader(doc, '5. CHAIN OF CUSTODY');
          for (const evt of report.custody) {
            doc.fontSize(9);
            doc.text(`${evt.eventTimestamp} | ${evt.eventType} | Actor: ${safePdfText(evt.actor)}`);
            if (evt.fromUser) doc.text(`  From: ${safePdfText(evt.fromUser)}`);
            if (evt.toUser) doc.text(`  To: ${safePdfText(evt.toUser)}`);
            if (evt.reason) doc.text(`  Reason: ${safePdfText(evt.reason)}`);
            doc.moveDown(0.2);
          }
        }

        // ─── Audit Trail ────────────────────────────────────
        if (report.audit.length > 0) {
          this.pdfSectionHeader(doc, '6. AUDIT TRAIL');
          for (const log of report.audit) {
            doc.fontSize(9);
            doc.text(`${log.timestamp} | ${log.action} | ${log.result} | ${safePdfText(log.actor)}`);
            doc.moveDown(0.1);
          }
        }

        // ─── AI Analysis ────────────────────────────────────
        if (report.aiAnalysis.length > 0) {
          this.pdfSectionHeader(doc, '7. AI ANALYSIS (ADVISORY ONLY)');
          doc.fontSize(8).fillColor('#b45309');
          doc.text('NOTICE: All AI-generated content is investigative assistance only. It does not constitute a confirmed forensic finding.');
          doc.fillColor('#000000').moveDown(0.3);

          for (const ai of report.aiAnalysis) {
            doc.fontSize(9).font('Helvetica-Bold');
            doc.text(`${ai.analysisType} — ${ai.status}`);
            doc.font('Helvetica');
            doc.text(`  Provider: ${safePdfText(ai.provider)} | Model: ${safePdfText(ai.model)}`);
            if (ai.summary) doc.text(`  Summary: ${safePdfText(ai.summary)}`);
            if (ai.errorMessage) doc.text(`  Error: ${safePdfText(ai.errorMessage)}`);
            if (ai.confidence !== null) doc.text(`  Confidence: ${(ai.confidence * 100).toFixed(1)}%`);
            doc.text(`  AI Input Hash: ${ai.aiInputHash}`);
            doc.moveDown(0.2);
          }
        }

        // ─── Summary ────────────────────────────────────────
        this.pdfSectionHeader(doc, 'EXECUTIVE SUMMARY');
        doc.fontSize(9).text(safePdfText(report.summary));
        doc.moveDown(0.5);

        // ─── Limitations ────────────────────────────────────
        if (report.limitations.length > 0) {
          this.pdfSectionHeader(doc, 'LIMITATIONS');
          doc.fontSize(9);
          for (const lim of report.limitations) {
            doc.text(`• ${safePdfText(lim)}`);
          }
          doc.moveDown(0.5);
        }

        // ─── Disclaimer ─────────────────────────────────────
        this.pdfHorizontalRule(doc);
        doc.fontSize(8).font('Helvetica-Oblique');
        doc.text(safePdfText(report.disclaimer));
        doc.moveDown(0.5);

        // ─── Report Hash Footer ─────────────────────────────
        doc.fontSize(7).font('Helvetica');
        doc.text(`Report Hash (SHA-256): ${report.reportMetadata.reportHash}`, { align: 'center' });

        doc.end();
      } catch (err) {
        reject(err);
      }
    });
  }

  /**
   * Render a structured report to safe HTML format.
   * All content is HTML-escaped to prevent XSS.
   */
  renderHTML(report: InvestigationReport): string {
    const h = escapeHtml;
    const sections: string[] = [];

    sections.push(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Investigation Report - ${h(report.reportMetadata.reportType)}</title>
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    body { font-family: 'Segoe UI', Arial, sans-serif; color: #1e293b; background: #fff; padding: 40px; max-width: 900px; margin: 0 auto; line-height: 1.5; font-size: 13px; }
    h1 { font-size: 22px; margin-bottom: 4px; color: #0f172a; }
    h2 { font-size: 15px; margin: 24px 0 8px; padding-bottom: 4px; border-bottom: 2px solid #e2e8f0; color: #1e40af; }
    .meta { background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 12px 16px; margin: 12px 0 20px; font-size: 12px; color: #475569; }
    .meta span { display: block; margin-bottom: 2px; }
    table { width: 100%; border-collapse: collapse; margin: 8px 0 16px; font-size: 12px; }
    th, td { padding: 6px 8px; text-align: left; border: 1px solid #e2e8f0; }
    th { background: #f1f5f9; font-weight: 600; color: #334155; }
    .advisory { background: #fffbeb; border: 1px solid #fbbf24; border-radius: 6px; padding: 8px 12px; margin: 8px 0; font-size: 11px; color: #92400e; }
    .disclaimer { margin-top: 24px; padding: 12px; background: #f8fafc; border-top: 2px solid #e2e8f0; font-size: 11px; font-style: italic; color: #64748b; }
    .hash { text-align: center; font-family: monospace; font-size: 10px; color: #94a3b8; margin-top: 16px; }
    .lim { margin: 4px 0; padding-left: 16px; }
  </style>
</head>
<body>`);

    // Title
    sections.push(`<h1>INVESTIGATION REPORT</h1>`);
    sections.push(`<p style="color:#64748b;font-size:14px;">${h(report.reportMetadata.reportType.replace(/_/g, ' '))}</p>`);

    // Metadata
    sections.push(`<div class="meta">`);
    sections.push(`<span><strong>Generated:</strong> ${h(report.reportMetadata.generatedAt)}</span>`);
    sections.push(`<span><strong>Generated By:</strong> ${h(report.reportMetadata.generatedBy.name)} (${h(report.reportMetadata.generatedBy.role)})</span>`);
    if (report.reportMetadata.caseNumber) sections.push(`<span><strong>Case:</strong> ${h(report.reportMetadata.caseNumber)}</span>`);
    if (report.reportMetadata.incidentNumber) sections.push(`<span><strong>Incident:</strong> ${h(report.reportMetadata.incidentNumber)}</span>`);
    if (report.reportMetadata.evidenceNumber) sections.push(`<span><strong>Evidence:</strong> ${h(report.reportMetadata.evidenceNumber)}</span>`);
    sections.push(`<span><strong>Classification:</strong> ${h(report.reportMetadata.classification ?? 'INTERNAL')}</span>`);
    sections.push(`</div>`);

    // Case
    if (report.case) {
      sections.push(`<h2>1. Case Identification</h2>`);
      sections.push(`<table><tbody>`);
      sections.push(`<tr><th>Case Number</th><td>${h(report.case.caseNumber)}</td></tr>`);
      sections.push(`<tr><th>Title</th><td>${h(report.case.title)}</td></tr>`);
      sections.push(`<tr><th>Status</th><td>${h(report.case.status)}</td></tr>`);
      sections.push(`<tr><th>Priority</th><td>${h(report.case.priority)}</td></tr>`);
      sections.push(`<tr><th>Severity</th><td>${h(report.case.severity)}</td></tr>`);
      sections.push(`<tr><th>Classification</th><td>${h(report.case.classification)}</td></tr>`);
      if (report.case.leadInvestigator) sections.push(`<tr><th>Lead Investigator</th><td>${h(report.case.leadInvestigator)}</td></tr>`);
      sections.push(`</tbody></table>`);
      if (report.case.description) sections.push(`<p>${h(report.case.description)}</p>`);
    }

    // Incidents
    if (report.incidents.length > 0) {
      sections.push(`<h2>2. Incidents</h2>`);
      sections.push(`<table><thead><tr><th>Number</th><th>Title</th><th>Type</th><th>Severity</th><th>Status</th></tr></thead><tbody>`);
      for (const inc of report.incidents) {
        sections.push(`<tr><td>${h(inc.incidentNumber)}</td><td>${h(inc.title)}</td><td>${h(inc.type)}</td><td>${h(inc.severity)}</td><td>${h(inc.status)}</td></tr>`);
      }
      sections.push(`</tbody></table>`);
    }

    // Evidence
    if (report.evidence.length > 0) {
      sections.push(`<h2>3. Evidence Inventory</h2>`);
      sections.push(`<table><thead><tr><th>Number</th><th>Filename</th><th>Type</th><th>SHA-256</th></tr></thead><tbody>`);
      for (const ev of report.evidence) {
        sections.push(`<tr><td>${h(ev.evidenceNumber)}</td><td>${h(ev.originalFilename)}</td><td>${h(ev.evidenceType)}</td><td style="font-family:monospace;font-size:10px;">${h(ev.sha256)}</td></tr>`);
      }
      sections.push(`</tbody></table>`);
    }

    // Integrity
    if (report.integrity.length > 0) {
      sections.push(`<h2>4. Evidence Integrity</h2>`);
      sections.push(`<table><thead><tr><th>Evidence</th><th>Status</th><th>Note</th></tr></thead><tbody>`);
      for (const integ of report.integrity) {
        sections.push(`<tr><td>${h(integ.evidenceNumber)}</td><td>${h(integ.integrityStatus)}</td><td>${h(integ.note)}</td></tr>`);
      }
      sections.push(`</tbody></table>`);
    }

    // Custody
    if (report.custody.length > 0) {
      sections.push(`<h2>5. Chain of Custody</h2>`);
      sections.push(`<table><thead><tr><th>Timestamp</th><th>Event</th><th>Actor</th><th>From</th><th>To</th></tr></thead><tbody>`);
      for (const evt of report.custody) {
        sections.push(`<tr><td>${h(evt.eventTimestamp)}</td><td>${h(evt.eventType)}</td><td>${h(evt.actor)}</td><td>${h(evt.fromUser ?? '-')}</td><td>${h(evt.toUser ?? '-')}</td></tr>`);
      }
      sections.push(`</tbody></table>`);
    }

    // Audit
    if (report.audit.length > 0) {
      sections.push(`<h2>6. Audit Trail</h2>`);
      sections.push(`<table><thead><tr><th>Timestamp</th><th>Action</th><th>Result</th><th>Actor</th></tr></thead><tbody>`);
      for (const log of report.audit) {
        sections.push(`<tr><td>${h(log.timestamp)}</td><td>${h(log.action)}</td><td>${h(log.result)}</td><td>${h(log.actor)}</td></tr>`);
      }
      sections.push(`</tbody></table>`);
    }

    // AI
    if (report.aiAnalysis.length > 0) {
      sections.push(`<h2>7. AI Analysis (Advisory Only)</h2>`);
      sections.push(`<div class="advisory">⚠️ All AI-generated content is investigative assistance only and does not constitute a confirmed forensic finding.</div>`);
      sections.push(`<table><thead><tr><th>Type</th><th>Status</th><th>Confidence</th><th>Summary</th><th>AI Input Hash</th></tr></thead><tbody>`);
      for (const ai of report.aiAnalysis) {
        sections.push(`<tr><td>${h(ai.analysisType)}</td><td>${h(ai.status)}</td><td>${ai.confidence !== null ? (ai.confidence * 100).toFixed(1) + '%' : 'N/A'}</td><td>${h(ai.summary ?? 'N/A')}</td><td style="font-family:monospace;font-size:10px;">${h(ai.aiInputHash)}</td></tr>`);
      }
      sections.push(`</tbody></table>`);
    }

    // Summary
    sections.push(`<h2>Executive Summary</h2>`);
    sections.push(`<p>${h(report.summary)}</p>`);

    // Limitations
    if (report.limitations.length > 0) {
      sections.push(`<h2>Limitations</h2>`);
      for (const lim of report.limitations) {
        sections.push(`<p class="lim">• ${h(lim)}</p>`);
      }
    }

    // Disclaimer
    sections.push(`<div class="disclaimer">${h(report.disclaimer)}</div>`);

    // Report Hash
    sections.push(`<div class="hash">Report Hash (SHA-256): ${h(report.reportMetadata.reportHash)}</div>`);

    sections.push(`</body></html>`);

    return sections.join('\n');
  }

  // ─── PDF Helpers ─────────────────────────────────────────

  private pdfSectionHeader(doc: PDFKit.PDFDocument, title: string): void {
    doc.moveDown(0.5);
    doc.fontSize(12).font('Helvetica-Bold').text(title);
    doc.moveDown(0.3);
    doc.font('Helvetica');
  }

  private pdfHorizontalRule(doc: PDFKit.PDFDocument): void {
    const y = doc.y;
    doc
      .moveTo(60, y)
      .lineTo(535, y)
      .strokeColor('#cccccc')
      .lineWidth(0.5)
      .stroke();
    doc.moveDown(0.5);
  }
}

export const reportRenderer = new ReportRenderer();
